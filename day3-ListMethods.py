#List Methods using a variable

a=[10,11,12,13,14,15]
a.append(8) #append adds a new value at end
a.sort() #sort arranges the elements by default in ascending order
a.reverse() #reversly arranges the element
a.insert(2,4) #inserts the value at index,element
a.pop(1) #deletes the element at the (location)
print(a) 
